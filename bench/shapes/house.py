# 建筑：坡屋顶小屋 + 烟囱 + 门洞 + 台阶
walls = box((1.2, 0.9, 0.7), (0, 0, 0.35))
roof = prism([(-0.6, 0.68), (0.6, 0.68), (0.0, 1.12)], 1.35, plane="YZ", offset=0.0)
chim = box((0.15, 0.15, 0.45), (0.35, 0.2, 1.05))
step = box((0.5, 0.25, 0.06), (0, -0.57, 0.03))
h = union(walls, roof, chim, step)
door = box((0.25, 0.2, 0.45), (0, -0.45, 0.285))
win = [box((0.2, 0.2, 0.18), (x, -0.45, 0.45)) for x in (-0.38, 0.38)]
difference(h, door, *win)
